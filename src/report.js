// The publishable half: a Markdown report and a badge.
//
// A coverage claim that hides its own scope is the thing this tool exists to
// avoid, so the report prints the exclusions beside the numbers, and the
// badge carries two figures rather than one: how much has been decided, and
// how much of it a person actually wrote. "Left as drafted" is honest, and it
// is counted, but it is never counted as human.

import fs from 'node:fs';
import path from 'node:path';
import { stats as statsOf, authorshipOf, EXCLUDED } from './ledger.js';

/** The badge's "human": rewritten by a person, or theirs to begin with. Edited is reported, not counted. */
const humanShare = (s) => (s.total ? (s.byAuthorship.written + s.byAuthorship.claimed) / s.total : 0);

const pct = (n, d) => (d === 0 ? '100%' : `${Math.round((n / d) * 100)}%`);

export function renderReport(project, ledger) {
  const s = statsOf(ledger);
  const replaced = ledger.entries.filter((e) => e.previous_ai_text);
  const L = [];

  L.push('# Copy provenance');
  L.push('');
  L.push(`Generated by \`slopchop report\` from \`${project.rel(project.ledgerPath)}\`. It counts every`);
  L.push('visitor-readable string in this repository and records who wrote it.');
  L.push('');
  L.push('| | strings | words |');
  L.push('|---|---:|---:|');
  const a = s.byAuthorship, aw = s.wordsByAuthorship;
  L.push(`| Written by a person | ${a.written} | ${aw.written.toLocaleString()} |`);
  L.push(`| A person's words from the start | ${a.claimed} | ${aw.claimed.toLocaleString()} |`);
  L.push(`| Drafted by a model, edited by a person | ${a.edited} | ${aw.edited.toLocaleString()} |`);
  L.push(`| Left as drafted, deliberately | ${s.byStatus['ai-fine']} | ${s.wordsByStatus['ai-fine'].toLocaleString()} |`);
  if (s.byStatus['ai-revised']) {
    L.push(`| Rewritten by a model, accepted unedited | ${s.byStatus['ai-revised']} | ${s.wordsByStatus['ai-revised'].toLocaleString()} |`);
  }
  L.push(`| Not yet reviewed | ${s.byStatus.unreviewed} | ${s.wordsByStatus.unreviewed.toLocaleString()} |`);
  if (s.byStatus.rewritten) {
    L.push(`| Written, not yet applied to source | ${s.byStatus.rewritten} | ${s.wordsByStatus.rewritten.toLocaleString()} |`);
  }
  L.push(`| **Total** | **${s.total}** | **${s.words.toLocaleString()}** |`);
  L.push('');
  if (s.excluded.total) {
    L.push(`Not counted above: **${s.excluded.total}** ${s.excluded.total === 1 ? 'string' : 'strings'} (${s.excluded.words.toLocaleString()} words) marked as not copy. Every one is listed under [Marked as not copy](#${notCopyAnchor(s.excluded.total)}).`);
    L.push('');
  }
  L.push(`Human-authored or deliberately accepted: **${pct(s.done, s.total)}** of strings.`);
  L.push(`A person's words: **${pct(a.written + a.claimed, s.total)}** of strings, **${pct(aw.written + aw.claimed, s.words)}** of words.`);
  L.push(`Edited from a model's draft: **${pct(a.edited, s.total)}** of strings, counted apart, because an edit leaves most of the model's words in place.`);
  L.push('');
  L.push(`Whether a replacement was a rewrite or small edits is what the person said when they saved it. SlopChop records it and does not check it.`);
  L.push('');
  L.push('## By tier');
  L.push('');
  L.push('| Tier | Decided | Total |');
  L.push('|---|---:|---:|');
  for (const tier of ['prose', 'helper', 'label']) {
    const t = s.byTier[tier];
    const name = { prose: 'Paragraphs (16+ words)', helper: 'Helper text (6–15 words)', label: 'Labels (1–5 words)' }[tier];
    L.push(`| ${name} | ${t.done} | ${t.total} |`);
  }
  L.push('');
  L.push('## Scope');
  L.push('');
  L.push('In scope:');
  L.push('');
  for (const g of project.config.include) L.push(`- \`${g}\``);
  L.push('');
  L.push('Out of scope, on purpose:');
  L.push('');
  for (const o of project.outOfScope) {
    L.push(`- \`${o.path}\`${o.reason ? `: ${o.reason}` : ''}`);
  }
  if (project.frozen.size) {
    L.push(`- Frozen constants (${[...project.frozen].map((f) => `\`${f}\``).join(', ')}): matched byte-for-byte by the program and never offered for rewriting.`);
  }
  const ignored = project.ignoreKeys || new Set();
  if (ignored.size) {
    L.push(`- Ignored keys in data files (${[...ignored].map((k) => `\`${k}\``).join(', ')}): facts rather than writing, never offered for review.`);
  }
  if (!project.outOfScope.length && !project.frozen.size && !ignored.size) L.push('- _Nothing declared._');
  L.push('');
  L.push(`## Replaced drafts (${replaced.length})`);
  L.push('');
  if (!replaced.length) {
    L.push('_None yet._');
  } else {
    L.push("Where a model's draft was replaced, both are kept. A replacement a model wrote and a person accepted unedited is marked as such.");
    L.push('');
    for (const e of replaced.slice(0, 400)) {
      L.push(`- \`${e.occurrences[0]?.file || '—'}\``);
      L.push(`  - draft: ${JSON.stringify(e.previous_ai_text)}`);
      const how = e.status === 'ai-revised' ? ' (model rewrite, accepted)'
        : e.status === 'human' && authorshipOf(e).kind === 'edited' ? ' (edited)' : '';
      L.push(`  - now${how}: ${JSON.stringify(e.text)}`);
    }
  }
  L.push('');

  // Every string left out of the totals, by name, with no cap. The report
  // is a public claim; an exclusion nobody can see would be a quiet edit to it.
  const notCopy = ledger.entries.filter((e) => EXCLUDED.has(e.status));
  L.push(`## Marked as not copy (${notCopy.length})`);
  L.push('');
  if (!notCopy.length) {
    L.push('_None._');
  } else {
    L.push('A reviewer marked these as not text a person reads: format strings, identifiers, code. They are left out of every count above and listed here so the call can be checked.');
    L.push('');
    for (const e of notCopy) {
      const o = e.occurrences[0];
      const more = e.occurrences.length > 1 ? ` (and ${e.occurrences.length - 1} more)` : '';
      L.push(`- \`${o ? `${o.file}:${o.line}` : '—'}\`${more}: ${JSON.stringify(e.text)}`);
      if (e.note) L.push(`  - note: ${JSON.stringify(e.note)}`);
    }
  }
  L.push('');
  return L.join('\n');
}

/** GitHub's anchor for the "Marked as not copy (n)" heading. */
const notCopyAnchor = (n) => `marked-as-not-copy-${n}`;

/** A shields.io endpoint payload. Point a badge at the raw file URL. */
export function badge(ledger) {
  const s = statsOf(ledger);
  const decided = s.total ? s.done / s.total : 1;
  const human = humanShare(s);
  return {
    schemaVersion: 1,
    label: 'copy',
    message: `${Math.round(decided * 100)}% reviewed · ${Math.round(human * 100)}% human`,
    color: decided >= 0.9 ? 'brightgreen' : decided >= 0.5 ? 'yellow' : 'orange',
  };
}

const COLORS = { brightgreen: '#4c1', green: '#97ca00', yellow: '#dfb317', orange: '#fe7d37', red: '#e05d44', grey: '#555' };

/** A flat SVG badge, for repos that would rather not call out to shields. */
export function badgeSvg({ label, message, color }) {
  const w = (t) => Math.round(t.length * 6.3 + 12);
  const lw = w(label);
  const mw = w(message);
  const fill = COLORS[color] || color || COLORS.grey;
  const esc = (t) => t.replace(/&/g, '&amp;').replace(/</g, '&lt;');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${lw + mw}" height="20" role="img" aria-label="${esc(label)}: ${esc(message)}">
<title>${esc(label)}: ${esc(message)}</title>
<clipPath id="r"><rect width="${lw + mw}" height="20" rx="3" fill="#fff"/></clipPath>
<g clip-path="url(#r)"><rect width="${lw}" height="20" fill="#555"/><rect x="${lw}" width="${mw}" height="20" fill="${fill}"/></g>
<g fill="#fff" text-anchor="middle" font-family="Verdana,Geneva,DejaVu Sans,sans-serif" font-size="11">
<text x="${lw / 2}" y="14">${esc(label)}</text>
<text x="${lw + mw / 2}" y="14">${esc(message)}</text>
</g>
</svg>
`;
}

/** Write the report, the badge JSON and the badge SVG. Returns their paths. */
export function writeReport(project, ledger) {
  const report = renderReport(project, ledger);
  fs.mkdirSync(path.dirname(project.reportPath), { recursive: true });
  fs.writeFileSync(project.reportPath, report);

  const b = badge(ledger);
  fs.mkdirSync(path.dirname(project.badgePath), { recursive: true });
  fs.writeFileSync(project.badgePath, JSON.stringify(b, null, 2) + '\n');
  const svgPath = project.badgePath.replace(/\.json$/, '') + '.svg';
  fs.writeFileSync(svgPath, badgeSvg(b));

  return { report: project.reportPath, badge: project.badgePath, svg: svgPath };
}
