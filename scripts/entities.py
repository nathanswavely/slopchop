# Regenerates src/extract/entities.js: every named character reference HTML
# defines, from the WHATWG list as Python's standard library carries it.
#
#   python scripts/entities.py > src/extract/entities.js

import html.entities
import sys

sys.stdout.reconfigure(encoding='utf-8', newline='\n')

names = {k[:-1]: v for k, v in html.entities.html5.items() if k.endswith(';')}
by_value = {}
for name in sorted(names):
    value = '+'.join('%x' % ord(c) for c in names[name])
    by_value.setdefault(value, []).append(name)
groups = sorted(by_value.items(), key=lambda kv: [int(x, 16) for x in kv[0].split('+')])
packed = [value + ':' + ','.join(ns) for value, ns in groups]

lines, line = [], ''
for g in packed:
    if line and len(line) + len(g) + 1 > 96:
        lines.append(line)
        line = ''
    line = (line + ' ' + g) if line else g
lines.append(line)

print('''// Every named character reference HTML defines (%d names), so source is
// decoded the way a browser decodes it: `&rarr;` is the arrow a visitor
// sees, and its ID is the arrow's.
//
// Generated by scripts/entities.py from the WHATWG list. Do not edit by hand.
//
// Node only. The bookmarklet reads markup the browser has already
// serialized, and bundles entities.browser.js in this module's place
// (bundle.js), which asks the browser instead of shipping the table.
//
// Packed as `codepoints:name,name` groups, code points in hex, joined by +.

const PACKED = [''' % len(names))
for l in lines:
    print("  '%s'," % l)
print('''].join(' ');

let table = null;

/** The text a named reference stands for, without its & and ;. Undefined if HTML defines no such name. */
export function namedEntity(name) {
  if (!table) {
    table = new Map();
    for (const group of PACKED.split(' ')) {
      const [cps, list] = group.split(':');
      const value = String.fromCodePoint(...cps.split('+').map((h) => parseInt(h, 16)));
      for (const n of list.split(',')) table.set(n, value);
    }
  }
  return table.get(name);
}''')
